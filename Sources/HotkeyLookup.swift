    static func lookup(actionName: String, appName: String?) -> Shortcut? {
        // Clean up action name (remove ellipsis, etc.)
        let cleanName = actionName
            .replacingOccurrences(of: "…", with: "")
            .replacingOccurrences(of: "...", with: "")
            .trimmingCharacters(in: .whitespaces)

        // Try app-specific first
        if let appName = appName {
            // Try exact app name
            if let appDict = appShortcuts[appName],
               let (key, mods) = appDict[cleanName] {
                return Shortcut(key: key, modifiers: mods, actionName: actionName)
            }

            // Try partial app name match (e.g., "Code" matches "Visual Studio Code")
            for (appKey, shortcuts) in appShortcuts {
                if appName.contains(appKey) || appKey.contains(appName) {
                    if let (key, mods) = shortcuts[cleanName] {
                        return Shortcut(key: key, modifiers: mods, actionName: actionName)
                    }
                }
            }
        }

        // Fall back to system shortcuts
        if let (key, mods) = systemShortcuts[cleanName] {
            return Shortcut(key: key, modifiers: mods, actionName: actionName)
        }

        // Try partial match (e.g., "Copy 3 Items" matches "Copy")
        for (name, (key, mods)) in systemShortcuts {
            if cleanName.hasPrefix(name) || cleanName.hasSuffix(name) {
                return Shortcut(key: key, modifiers: mods, actionName: actionName)
            }
        }

        // Try contains match for system shortcuts
        for (name, (key, mods)) in systemShortcuts {
            if cleanName.localizedCaseInsensitiveContains(name) && name.count >= 4 {
                return Shortcut(key: key, modifiers: mods, actionName: actionName)
            }
        }

        return nil
    }
